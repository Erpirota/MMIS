def pluralize(count: int, singular: str, plural: str | None = None) -> str:
    """Format count with grammatically correct singular or plural form."""
    if count == 1:
        return f"{count} {singular}"
    if plural is None:
        plural = f"{singular}s"
    return f"{count} {plural}"


